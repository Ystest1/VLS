<div class="wp-block-group vp-faq__liste"><!-- wp:details {"showContent":true} -->
<details class="wp-block-details" open><summary>Qui sera mon locataire ?</summary><!-- wp:paragraph -->
<p>VALORIS PATRIMOINE. Vous signez le contrat avec notre société, qui devient votre locataire contractuel et votre interlocuteur unique.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Le loyer dépend-il du taux d'occupation ?</summary><!-- wp:paragraph -->
<p>Non. Le loyer mensuel fixe prévu au contrat ne dépend pas du nombre de jours pendant lesquels le logement est occupé. Il est versé selon les modalités prévues au contrat, sous réserve de l'exécution des obligations contractuelles.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>[À VALIDER : date et mode de versement du loyer]</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Qui occupe mon appartement ?</summary><!-- wp:paragraph -->
<p>Des professionnels en déplacement : consultants, salariés en mission, techniciens, équipes de maintenance et collaborateurs d'entreprise. Le logement est mis à disposition pour des besoins professionnels.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Quel est le rôle de VALORIS PATRIMOINE dans l'organisation du logement ?</summary><!-- wp:paragraph -->
<p>En tant que locataire contractuel, VALORIS PATRIMOINE organise l'utilisation du logement par des professionnels : arrivées et départs, suivi opérationnel, ménage, linge et entretien courant selon le périmètre convenu. Pour toute question sur le logement, vous vous adressez à notre société.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>[À VALIDER : étendue exacte des responsabilités de VALORIS PATRIMOINE vis-à-vis du propriétaire, notamment en cas de dégradation]</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Comment le logement est-il suivi et entretenu ?</summary><!-- wp:paragraph -->
<p>Le suivi opérationnel et l'entretien courant sont assurés par VALORIS PATRIMOINE selon le contrat.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>[À VALIDER : fréquence des passages ou contrôles, répartition entre entretien courant et travaux à la charge du propriétaire]</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Qui s'occupe du ménage et du linge ?</summary><!-- wp:paragraph -->
<p>VALORIS PATRIMOINE organise le ménage et la gestion du linge selon le périmètre prévu au contrat.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>[À VALIDER : fourniture du linge, fréquence du ménage, prise en charge des frais]</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Comment sont encadrées les occupations successives ?</summary><!-- wp:paragraph -->
<p>Le logement est mis à disposition de professionnels pour des besoins professionnels. Entre deux occupations, VALORIS PATRIMOINE organise la sortie, le ménage, le linge et l'entrée suivante.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>[À VALIDER : règles appliquées aux occupants — durée minimale de séjour, nombre maximal d'occupants, règlement intérieur, vérifications effectuées]</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Comment et quand puis-je récupérer mon logement ?</summary><!-- wp:paragraph -->
<p>Selon les modalités et le préavis prévus au contrat. La durée du contrat et les conditions de restitution sont fixées avant la signature.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>[À VALIDER : durée type du contrat, préavis, conditions de restitution et état des lieux de sortie]</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Quelles assurances, quels états des lieux, quel dépôt de garantie ?</summary><!-- wp:paragraph -->
<p>[À VALIDER : assurance réellement souscrite et nature de la couverture ; réalisation d'états des lieux d'entrée et de sortie ; existence et montant d'un dépôt de garantie. Aucune réponse ne sera publiée tant que ces éléments ne sont pas en place et documentés.]</p>
